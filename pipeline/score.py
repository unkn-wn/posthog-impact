"""Turn line history and review data into the published numbers, once per window.

Four measures make three scores, each computed without hand-picked weights. The
names on the page, then the name of the code that computes each one:

  Built on   Model.reach. Later PRs by other people that edited next to your
             lines. Each person has one vote, split across whose code they built
             on, then PageRank runs on those votes. Shipping more PRs, by hand
             or by agent, adds no votes.
  Held up    Model.held_up. Fewer later fixes than peers working in the same
             areas, on code of the same age. Multiplies Built on, making score 1.
  Areas      Model.breadth, score 2. h-index across areas: h areas with at least
             h built-on PRs each.
  Reviews    attention, score 3. PageRank over written reviews from people,
             excluding reviews that disclose they came from an agent.

The scores are combined by sampling 100,000 random weightings and counting how
often each person lands in the top 5, so no single weighting is ever chosen.
"""
import collections
import json
import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import numpy as np

from config import DAY, LINE_HISTORY, DATA, PUBLISHED, RAW, TOP, WEEK, WINDOWS

MAX_WEEK = 30  # held-up tables stop at this age, comfortably past the tracked history
AGE_HORIZON = 13  # weeks of older PRs used to learn how credit arrives, must fit in run.HISTORY_DAYS
MIN_EXPOSURE = 1000  # line-weeks of peer code before an area baseline is trusted
DAMPING = 0.85  # PageRank convention
SAMPLES = 100_000
SEED = 7
REVIEWS_COLUMN = 2  # position of the Reviews score in Scenario.table

BOT = re.compile(
    r"\[bot\]$|-bot$|^posthog$|-posthog(-.*)?$|^trunk-io$|^stamphog$|-ai$|^copilot|coderabbit|greptile|dependabot|renovate",
    re.I,
)
AGENT_REVIEW = re.compile(
    r"automated review|on behalf of @|^\s*\U0001F916|generated by|reviewed by (claude|codex|an agent)|ai review|agent review",
    re.I,
)
MECHANICAL = re.compile(r"\bregenerat|\bre-generate\b|\bcodegen\b|\bupdate (the )?snapshots?\b", re.I)
TRIVIAL = re.compile(r"^\W*(lgtm|looks good|approved?|ship it|thanks?( you)?|nice|ty|great|\+1)?\W*$", re.I)


def is_bot(actor):
    return not actor or actor["__typename"] != "User" or bool(BOT.search(actor["login"]))


def load_prs(raw_dir):
    prs = {}
    for path in sorted(raw_dir.glob("*.json")):
        for pr in json.loads(path.read_text(encoding="utf-8")):
            prs[pr["number"]] = pr
    return prs


def percentile(values):
    """Share of the population each person is at or above, ties averaged."""
    values = np.asarray(values, dtype=float)
    _, inverse, counts = np.unique(values, return_inverse=True, return_counts=True)
    upper = np.cumsum(counts) - 1
    return (upper - (counts - 1) / 2)[inverse] / (len(values) - 1)


def pagerank_arrays(source, target, weight, n):
    """Each person gets one vote, split across the people they point to."""
    outgoing = np.bincount(source, weight, n)
    share = weight / outgoing[source]
    rank = np.ones(n) / n
    for _ in range(100):
        spread = np.bincount(target, rank[source] * share, n)
        next_rank = (1 - DAMPING) / n + DAMPING * (spread + rank[outgoing == 0].sum() / n)
        if np.abs(next_rank - rank).sum() < 1e-9:
            return next_rank
        rank = next_rank
    return rank


def pagerank(edges, people):
    index = {p: i for i, p in enumerate(people)}
    pairs = [(index[a], index[b], w) for (a, b), w in edges.items() if a in index and b in index]
    if not pairs:
        return dict.fromkeys(people, 1 / len(people))
    source, target, weight = map(np.array, zip(*pairs))
    return dict(zip(people, pagerank_arrays(source, target, weight.astype(float), len(people))))


def acceptability(table):
    """Sample weightings uniformly and count top-5 finishes."""
    rng = np.random.default_rng(SEED)
    weights = rng.dirichlet((1, 1, 1), SAMPLES)
    top = np.zeros(len(table))
    for start in range(0, SAMPLES, 10_000):
        scores = table @ weights[start:start + 10_000].T
        best = np.argpartition(-scores, TOP - 1, axis=0)[:TOP]
        top += np.bincount(best.ravel(), minlength=len(table))
    return top / SAMPLES


def attention(prs):
    """Who wrote real reviews for whom, as edges from the author to each reviewer."""
    edges = collections.Counter()
    given = collections.Counter()
    written_prs = 0
    for pr in prs:
        author = pr["author"]
        if is_bot(author):
            continue
        reviews = [(r["author"], r["bodyText"]) for r in pr["reviews"]["nodes"]]
        comments = [
            (c["author"], c["bodyText"])
            for thread in pr["reviewThreads"]["nodes"]
            for c in thread["comments"]["nodes"]
        ]
        reviewers = {
            actor["login"]
            for actor, text in reviews + comments
            if not is_bot(actor) and actor["login"] != author["login"]
            and not TRIVIAL.match(text) and not AGENT_REVIEW.search(text)
        }
        written_prs += bool(reviewers)
        for login in reviewers:
            edges[(author["login"], login)] += 1
            given[login] += 1
    return edges, given, written_prs


class Model:
    """Who owns each commit, and how often code gets corrected. Shared by every window."""

    def __init__(self, replay, prs):
        self.end = replay["end_time"]
        self.commits = replay["commits"]
        self.built_on = replay["built_on"]
        self.ended = replay["ended"]
        self.areas = replay["areas"]
        self.prs = prs

        names = collections.defaultdict(collections.Counter)
        for commit in self.commits:
            pr = prs.get(commit["pr"])
            if pr and pr["author"]:
                names[commit["author"]][pr["author"]["login"]] += 1
        name_to_login = {name: c.most_common(1)[0][0] for name, c in names.items()}
        self.display = {}
        for name, login in name_to_login.items():
            self.display.setdefault(login, name)

        self.owner, self.human, self.autonomous = [], [], []
        for commit in self.commits:
            pr = prs.get(commit["pr"])
            if pr:
                login = pr["author"]["login"] if pr["author"] else None
                human = not is_bot(pr["author"])
                autonomous = pr["autonomy"] == "autonomous"
            else:
                login = name_to_login.get(commit["author"], commit["author"])
                human = not BOT.search(commit["author"]) and not BOT.search(login)
                autonomous = False
            self.owner.append(login)
            self.human.append(human)
            self.autonomous.append(autonomous)
        self.mechanical = [bool(MECHANICAL.search(c["title"])) for c in self.commits]
        self._measure_correction_rates()

    def reach(self, keep, in_window):
        """One (builder, origin, value) vote per later edit next to a kept commit.

        keep says which commits can earn credit. Each later PR splits one unit
        across the code it touched, then the value is raised for young commits
        by how much credit older commits (outside in_window) had by that age.
        """
        pending = []
        older = collections.Counter()
        for index, touched in enumerate(self.built_on):
            if not touched or not self.human[index] or self.autonomous[index]:
                continue
            author = self.owner[index]
            valid = [(o, lines) for o, lines in touched if self.human[o] and self.owner[o] != author]
            total = sum(lines for _, lines in valid)
            for origin, lines in valid:
                share = lines / total
                if keep[origin]:
                    pending.append((author, origin, share))
                if not in_window[origin]:
                    older[(self.commits[index]["date"] - self.commits[origin]["date"]) // WEEK] += share

        by_week = np.array([older[week] for week in range(AGE_HORIZON)])
        arrived = np.cumsum(by_week) / (by_week.sum() or 1)
        arrived[arrived == 0] = 1  # nothing to learn from at this age, so no correction

        votes = []
        for author, origin, share in pending:
            age = (self.end - self.commits[origin]["date"]) // WEEK
            votes.append((author, origin, share / arrived[min(age, AGE_HORIZON - 1)]))
        return votes

    def _measure_correction_rates(self):
        """Exposure and corrections by area and week, for everyone and per person."""
        zeros = lambda: np.zeros(MAX_WEEK)
        self.area_risk = collections.defaultdict(zeros)
        self.area_event = collections.defaultdict(zeros)
        self.person_risk = collections.defaultdict(zeros)
        self.person_event = collections.defaultdict(zeros)
        sizes = []
        for origin, area, kind, weeks, lines in self.ended:
            if not self.human[origin]:
                continue
            person = self.owner[origin]
            week = capped_week(weeks)
            self.area_risk[area][:week + 1] += lines
            self.person_risk[(person, area)][:week + 1] += lines
            if kind == "corrected":
                self.area_event[area][week] += lines
                self.person_event[(person, area)][week] += lines
                sizes.append(lines)
        sizes = np.array(sizes, dtype=float)
        # Corrected lines arrive in clumps, so count clumps rather than lines.
        self.clump = float((sizes ** 2).sum() / sizes.sum()) if len(sizes) else 1.0
        self.global_risk = sum(self.area_risk.values(), zeros())
        self.global_event = sum(self.area_event.values(), zeros())

    def held_up(self, keep):
        """Observed versus expected corrections, with the person left out of the baseline."""
        window_risk = collections.defaultdict(lambda: np.zeros(MAX_WEEK))
        observed_by_person = collections.Counter()
        origin_observed = collections.Counter()
        origin_expected = collections.Counter()

        for origin, area, kind, weeks, lines in self.ended:
            if keep[origin]:
                window_risk[(origin, area)][:capped_week(weeks) + 1] += lines
                if kind == "corrected":
                    observed_by_person[self.owner[origin]] += lines
                    origin_observed[origin] += lines

        expected_by_person = collections.Counter()
        for (origin, area), risk in window_risk.items():
            person = self.owner[origin]
            own_risk = self.person_risk[(person, area)]
            own_event = self.person_event[(person, area)]
            peer_risk = self.area_risk[area] - own_risk
            peer_event = self.area_event[area] - own_event
            fallback = (self.global_event - own_event) / np.maximum(self.global_risk - own_risk, 1)
            local = peer_event / np.maximum(peer_risk, 1)
            # In an area one person dominates, "peers" are too few to compare with.
            trusted = (peer_risk >= MIN_EXPOSURE) & (peer_risk >= own_risk)
            value = float((risk * np.where(trusted, local, fallback)).sum())
            expected_by_person[person] += value
            origin_expected[origin] += value

        # Empirical-Bayes shrinkage toward 1: estimate how much people really
        # differ beyond Poisson noise (method of moments), then pull each ratio
        # toward average in proportion to how little evidence that person has.
        people = [p for p in expected_by_person if expected_by_person[p] > 0]
        observed = np.array([observed_by_person[p] for p in people]) / self.clump
        expected = np.array([expected_by_person[p] for p in people]) / self.clump
        variance = max(((observed - expected) ** 2 - expected).sum() / (expected ** 2).sum(), 0) if people else 0

        result = {
            person: {
                "held": (e * variance + 1) / (o * variance + 1),
                "observed": observed_by_person[person],
                "expected": round(expected_by_person[person], 1),
            }
            for person, o, e in zip(people, observed, expected)
        }
        return result, {"variance": variance, "origin_observed": origin_observed, "origin_expected": origin_expected}

    def breadth(self, credited):
        by_person = collections.defaultdict(collections.Counter)
        for origin in credited:
            by_person[self.owner[origin]].update(self.areas[origin])
        result = {}
        for person, counts in by_person.items():
            ordered = sorted(counts.values(), reverse=True)
            result[person] = sum(1 for i, c in enumerate(ordered, 1) if c >= i)
        return result


def capped_week(weeks):
    return min(max(weeks, 0), MAX_WEEK - 1)


@dataclass
class Window:
    days: int
    in_window: list  # per commit
    keep: list  # per commit: can it earn credit here
    prs: list  # every PR merged in the window, including ones that only touch excluded files
    human_prs: list
    people: list
    reviews_given: collections.Counter
    written_prs: int  # PRs with a real written review
    reviews_rank: dict


def open_window(model, days):
    start = model.end - days * DAY
    in_window = [c["pr"] in model.prs and c["date"] >= start for c in model.commits]
    keep = [i and h and not m for i, h, m in zip(in_window, model.human, model.mechanical)]
    prs = [p for p in model.prs.values() if datetime.fromisoformat(p["mergedAt"]).timestamp() >= start]
    human_prs = [p for p in prs if not is_bot(p["author"])]
    edges, given, written_prs = attention(prs)
    people = sorted({p["author"]["login"] for p in human_prs} | set(given))
    if len(people) < TOP:
        raise ValueError(f"{days}d window has {len(people)} people, need at least {TOP}")
    return Window(days, in_window, keep, prs, human_prs, people, given, written_prs, pagerank(edges, people))


@dataclass
class Scenario:
    credit: dict  # origin -> credit
    votes: list  # (builder, origin, value)
    held: dict
    held_info: dict
    breadth: dict
    table: np.ndarray  # one row per person: percentile on each score
    share: np.ndarray  # per person: fraction of weightings with them in the top 5
    order: list  # people, best first


def scenario(model, window, keep):
    """Score one choice of which commits count."""
    votes = model.reach(keep, window.in_window)
    held, held_info = model.held_up(keep)
    credit = collections.Counter()
    edges = collections.Counter()
    for builder, origin, value in votes:
        credit[origin] += value
        edges[(builder, model.owner[origin])] += value
    breadth = model.breadth(credit)
    reach = pagerank(edges, window.people)
    people = window.people
    table = np.column_stack([
        percentile([reach[p] * held[p]["held"] if p in held else reach[p] for p in people]),
        percentile([breadth.get(p, 0) for p in people]),
        percentile([window.reviews_rank[p] for p in people]),
    ])
    share = acceptability(table)
    order = sorted(range(len(people)), key=lambda i: (-share[i], -table[i].sum()))
    return Scenario(credit, votes, held, held_info, breadth, table, share, [people[i] for i in order])


def person_cards(model, window, full, directed):
    """The published facts for the top 5.

    top5                 percent of weightings that put them in the top 5
    held                 expected over observed fixes after shrinkage, above 1 is better
    attention            percentile on Reviews, 0 to 100
    reviews              PRs they gave a real written review on
    volumeRank           position by merged PRs, None if they merged none
    rankWithoutAutonomous  rank with self-declared autonomous PRs removed
    """
    pr_counts = collections.Counter(p["author"]["login"] for p in window.human_prs)
    autonomous_counts = collections.Counter(
        p["author"]["login"] for p in window.human_prs if p["autonomy"] == "autonomous"
    )
    volume_rank = {p: rank for rank, (p, _) in enumerate(pr_counts.most_common(), 1)}
    directed_rank = {p: rank for rank, p in enumerate(directed.order, 1)}
    index_of = {p: i for i, p in enumerate(window.people)}

    builders = collections.defaultdict(set)
    for builder, origin, _ in full.votes:
        builders[model.owner[origin]].add(builder)
    credited_prs = collections.defaultdict(list)
    for origin, value in full.credit.items():
        credited_prs[model.owner[origin]].append((value, origin))

    def card(person):
        i = index_of[person]
        held = full.held.get(person, {"held": 1.0, "observed": 0, "expected": 0.0})
        return {
            "login": person,
            "name": model.display.get(person, person),
            "top5": round(float(full.share[i]) * 100, 1),
            "rankWithoutAutonomous": directed_rank[person],
            "builders": len(builders[person]),
            "held": round(held["held"], 2),
            "corrected": held["observed"],
            "expectedCorrected": held["expected"],
            "breadth": full.breadth.get(person, 0),
            "attention": round(float(full.table[i][REVIEWS_COLUMN]) * 100),
            "reviews": window.reviews_given[person],
            "prs": pr_counts[person],
            "autonomous": autonomous_counts[person],
            "volumeRank": volume_rank.get(person),
            "evidence": [{
                "number": model.commits[origin]["pr"],
                "title": re.sub(r"\s*\(#\d+\)\s*$", "", model.commits[origin]["title"]),
            } for _, origin in sorted(credited_prs[person], reverse=True)[:3]],
        }

    return [card(person) for person in full.order[:TOP]]


def score_window(model, days):
    window = open_window(model, days)
    full = scenario(model, window, window.keep)

    # The same ranking with self-declared autonomous PRs taken out.
    directed = scenario(model, window, [k and not a for k, a in zip(window.keep, model.autonomous)])

    # Does the top 5 depend on one PR? Remove each person's biggest and re-rank.
    # Sorted ascending, so each person's entry ends up holding their largest.
    biggest = {model.owner[origin]: origin for origin in sorted(full.credit, key=full.credit.get)}
    trimmed_keep = list(window.keep)
    for origin in biggest.values():
        trimmed_keep[origin] = False
    trimmed = scenario(model, window, trimmed_keep)

    start = model.end - days * DAY
    numbered = [c["pr"] for c in model.commits if c["date"] >= start and c["pr"]]
    human_count = len(window.human_prs)
    declared = sum(p["autonomy"] in ("directed", "autonomous") for p in window.human_prs)
    return {
        "days": days,
        "humanPrs": human_count,
        "people": len(window.people),
        "coverage": round(100 * sum(n in model.prs for n in numbered) / len(numbered), 1),
        "declaredAgent": round(100 * declared / human_count, 1),
        "writtenReviewPrs": round(100 * window.written_prs / human_count, 1),
        "heldMeasured": bool(full.held_info["variance"] > 0),  # shrinkage found real differences between people
        "sameTop5WithoutBiggestPr": set(full.order[:TOP]) == set(trimmed.order[:TOP]),
        "top": person_cards(model, window, full, directed),
    }


def run(line_history, raw_dir, out):
    replay = json.loads(line_history.read_text(encoding="utf-8"))
    model = Model(replay, load_prs(raw_dir))
    windows = [score_window(model, days) for days in WINDOWS]
    text = json.dumps({"snapshot": replay["end_time"], "samples": SAMPLES, "windows": windows}, indent=1, allow_nan=False)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")

    for window in windows:
        names = ", ".join(f"{p['login']} {p['top5']}%" for p in window["top"])
        print(f"{window['days']}d: {window['humanPrs']} PRs, {window['people']} people\n  {names}", flush=True)


if __name__ == "__main__":
    run(DATA / LINE_HISTORY, DATA / RAW, PUBLISHED)
